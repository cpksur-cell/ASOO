/**
 * Polygons for Jordan's twelve governorates.
 *
 * SOURCE: Natural Earth 1:10m Admin 1 — States, Provinces (public domain).
 * Extracted for `adm0_a3 = 'JOR'`, simplified with Douglas–Peucker at a
 * 0.012° tolerance (roughly 1 km), and converted from GeoJSON [lng, lat]
 * to the [lat, lng] pairs the globe projects. Regenerated rather than hand-
 * traced, which is how the previous version came to place Amman's eastern
 * edge at 37.6°E — about 95 km into Mafraq — and left gaps where neighbours
 * failed to meet.
 *
 * Coordinates are WGS 84 decimal degrees. Rings are open: the renderer closes
 * them.
 *
 * ACCURACY: these are CARTOGRAPHIC, not cadastral. Natural Earth is a
 * small-scale mapping dataset and the rings are further simplified so a hero
 * canvas can redraw them every frame. Nothing here is a survey product and no
 * boundary dispute should ever be read off it — the authoritative source is
 * the Department of Lands and Survey.
 *
 * `code` keys into the governorate records that already back the directory, so
 * names stay translated in one place (CLAUDE.md §9) and no place name is
 * duplicated as a literal here.
 */

export interface GovernorateShape {
  code: string
  /** [lat, lng] pairs. */
  ring: Array<[number, number]>
  /** Where the name sits — the point furthest from any edge, so a label lands
   *  inside a wedge-shaped governorate rather than in a neighbour. */
  labelAt: [number, number]
}

